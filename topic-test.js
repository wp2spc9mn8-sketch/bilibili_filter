const pad = (s, n) => {
  let w = 0, o = '';
  for (const c of String(s)) {
    w += /[\u4e00-\u9fa5]/.test(c) ? 2 : 1;
    if (w > n) return o + '…';
    o += c;
  }
  return o + ' '.repeat(Math.max(0, n - w));
};

