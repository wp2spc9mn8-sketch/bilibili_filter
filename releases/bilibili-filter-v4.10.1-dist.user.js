      lifestyle: true,     // 生活方式：穿搭、减肥、医美、装修、独居
      parenting: true,     // 育儿鸡汤：聪明妈妈、鸡娃、兴趣班
      career: true,        // 职场叙事：裸辞、被裁、大厂真实一天
      quiz: true,          // 心理测试：MBTI、测测你、自测量表
      warPorn: true,       // 军事爽文：美军这次栽了、战争背后的真相
