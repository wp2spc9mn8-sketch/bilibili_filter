console.log('\n===== weak 列表：同一个词只能出现一次 =====');
{
  // 从源码抽出每个话题的 weak 数组，检查正则源码是否重复
  const m = src.match(/const TOPICS = \{[\s\S]*?\n  \};/);
  const block = m ? m[0] : '';
  let dup = 0;
  // 简化判断：统计 weak 段里每个 /.../ 的源码出现次数
  const weakSegs = block.split(/\n\s*weak:\s*\[/).slice(1);
  for (const seg of weakSegs) {
    const body = seg.split(']')[0];
    const regs = (body.match(/\/[^/\n]+\//g) || []);
    const seen = new Map();
    for (const r of regs) seen.set(r, (seen.get(r) || 0) + 1);
    for (const [r, n] of seen) {
      if (n > 1) { dup++; console.log(` FAIL  重复 ${r} ×${n}`); }
    }
  }
  console.log(dup === 0 ? ' PASS  无重复词' : ` 共 ${dup} 处重复`);
  bad += dup;
}

